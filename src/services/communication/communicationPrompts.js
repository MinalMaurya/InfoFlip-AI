export function buildCommunicationUserPrompt(request, options = {}) {
  const {
    sourceId = 'src-1',
    sourceContent = {},
    analysis = {},
    transformationOutputs = [],
    config = {},
    requestedChannels = []
  } = request;

  const rawText = sourceContent.extractedText || sourceContent.rawText || '';

  const isRegen = Boolean(options.isRegeneration || options.variantSeed);
  const regenDirective = isRegen ? `
==============================
🔄 REGENERATION VARIANT DIRECTIVE
==============================
- This is a REGENERATION request for a new candidate variation.
- Generate a fresh, distinct candidate variation with alternative framing, wording, and hooks.
- Strictly maintain 100% adherence to all grounded source facts and figures.
` : '';

  // Summarize key facts from Module 2
  const factsList = Array.isArray(analysis.keyFacts)
    ? analysis.keyFacts.map((f, i) => `${i + 1}. ${typeof f === 'string' ? f : f.fact}`).join('\n')
    : 'None detected.';

  // Summarize numbers & dates
  const datesList = Array.isArray(analysis.importantDates)
    ? analysis.importantDates.map(d => `${d.date} (${d.context || ''})`).join(', ')
    : 'None';
  const numbersList = Array.isArray(analysis.importantNumbers)
    ? analysis.importantNumbers.map(n => `${n.value} (${n.label || n.context || ''})`).join(', ')
    : 'None';

  // Summarize Module 3 transformation outputs if available
  let mod3Summary = '';
  if (Array.isArray(transformationOutputs) && transformationOutputs.length > 0) {
    mod3Summary = transformationOutputs.map(out => {
      const format = out.format || out.channelId || 'format';
      const contentStr = typeof out.content === 'string' 
        ? out.content.slice(0, 300) 
        : JSON.stringify(out.content).slice(0, 300);
      return `[Module 3 Output - ${format}]:\n${contentStr}...`;
    }).join('\n\n');
  }

  // Format channel-specific guidelines
  const channelInstructions = requestedChannels.map(channelId => {
    const channelDef = getCommunicationChannelById(channelId);
    if (!channelDef) return `- ${channelId}: Generate standard communication asset.`;
    return `### Channel: ${channelDef.name} (${channelDef.id})
Max Characters: ${channelDef.maxCharacters}
Instructions:
${channelDef.promptInstructions}`;
  }).join('\n\n');

  const isEmerg = isEmergencyContent(request);
  const emergencySection = isEmerg ? `
==============================
⚠️ EMERGENCY & PUBLIC SAFETY DIRECTIVE
==============================
- This request is classified as URGENT PUBLIC SAFETY / DISASTER RESPONSE.
- For LinkedIn:
  * Prioritize clear safety instructions, essential actions, and concise scannable bullet points over promotional language.
  * NEVER include generic engagement questions like "What are your thoughts on this?". Use official directives / helplines.
  * Single clear title. DO NOT output repetitive headings (e.g. no "Key Development" followed by "Strategic Update").
  * Use 3-5 readable hashtags (e.g. #WeatherAlert, #PublicSafety, #DisasterPreparedness). Avoid extremely long concatenated hashtags.
- Ground all guidance strictly in source facts. DO NOT invent alert tiers, unstated helplines, or imaginary casualty figures.
` : '';

  const targetAudienceStr = typeof config.targetAudience === 'string'
    ? config.targetAudience
    : (Array.isArray(config.targetAudience) ? config.targetAudience.join(', ') : 'General Public');

  const audienceDirective = getAudienceDirectives(targetAudienceStr);
  const toneDirective = getToneDirectives(config.tone);
  const detailDirective = getDetailDirectives(config.detailLevel);
  const objectiveDirective = getObjectiveDirectives(config.objective);
  const styleDirective = getStyleDirectives(config.contentStyle || config.style);
  const languageDirective = getLanguageDirectives(config.language);

  return `Please generate communication-ready assets for the following requested channels:
Requested Channels: ${requestedChannels.join(', ')}
${regenDirective}
${emergencySection}
==============================
CONFIGURATION & ACTIVE DIRECTIVES
==============================
Target Audience: ${targetAudienceStr}
  * Directive: ${audienceDirective}
Tone: ${config.tone || 'Informative'}
  * Directive: ${toneDirective}
Language: ${config.language || 'English'}
  * Directive: ${languageDirective}
Detail Level: ${config.detailLevel || 'Balanced'}
  * Directive: ${detailDirective}
Objective: ${config.objective || 'Inform'}
  * Directive: ${objectiveDirective}
Content Style: ${config.contentStyle || config.style || 'Structured'}
  * Directive: ${styleDirective}

==============================
GROUND TRUTH & FACTS
==============================
Source ID: ${sourceId}
Main Topic: ${analysis.overview?.mainTopic || 'Not specified'}
Source Text (Ground Truth):
${rawText}

Grounded Key Facts from Source (Module 2):
${factsList}

Important Dates: ${datesList}
Important Numbers / Statistics: ${numbersList}
Urgency Level: ${analysis.urgency?.level || 'Standard'}

==============================
MODULE 3 STRUCTURED CONTENT (Base reference)
==============================
${mod3Summary || 'Direct adaptation from source and analysis.'}

==============================
CHANNEL-SPECIFIC REQUIREMENTS
==============================
${channelInstructions}

Generate the outputs array in JSON format. Ground every factual claim in the provided source/analysis facts.`;
}
